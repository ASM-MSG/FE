/**
 * 분석 진행 바의 의사 진행률 (기준 3, D7) — 경과 시간(ms)만 받는 순수 함수.
 *
 * `POST /api/videos/highlight-preview`는 동기 API라 진행률 정보를 주지 않는다. 웹은 이
 * 때문에 확정형 진행 바를 의도적으로 버렸지만(AnalyzingModal 주석), MSG-424 티켓은 진행
 * 바와 예상 소요 시간을 명시적으로 요구하므로 티켓 요구를 우선한다 — **웹과 의도적으로
 * 달라지는 지점**이다(검증에서 웹 대조로 결함 판정하지 않는다).
 *
 * 점근 곡선이라 응답 도착 전에는 어떤 경과 시간에도 100%에 도달하지 않는다 — 진행 바가
 * 꽉 찬 채로 멈춰 있는(=끝난 것처럼 보이는) 상태를 만들지 않기 위한 성질이다.
 * 100% 채움은 응답이 도착해 화면이 전환될 때만 일어난다.
 */

/** 점근 상한 — 응답 전에는 이 값에 수렴할 뿐 넘지 않는다 */
const ASYMPTOTE = 0.95;

/**
 * 시상수(ms) — Figma 캡션 "보통 10~20초 정도 걸려요"에 맞춘 체감 속도.
 * 10초에 약 54%, 20초에 약 77%를 지난다.
 */
const TIME_CONSTANT_MS = 12_000;

/** 경과 시간(ms) → 0 이상 1 미만의 진행 비율. 음수 경과(시각 역행)는 0으로 바닥친다. */
export const analysisProgress = (elapsedMs: number): number =>
  ASYMPTOTE * (1 - Math.exp(-Math.max(0, elapsedMs) / TIME_CONSTANT_MS));
