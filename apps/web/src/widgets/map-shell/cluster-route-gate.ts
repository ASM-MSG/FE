import { ROUTES } from "@/app/routes";

/**
 * 저줌 집계 마커의 경로 게이트 (MSG-489 §12, 사용자 지시 2026-08-29).
 *
 * 지시 원문: "ai 경로 추천인 상태에서는 다른 애들 클러스터링 된 것들 안보이게 해 /
 * 한마디로 줌레벨 100m보다 커지면 더 이상 지도상에서 안 보이게 하라는 뜻이야".
 * 집계 마커(지역 점령·미션·핫구역) 3종은 **줌 16(100m) 미만에서만** 존재하는 층이라
 * — 16 이상에서는 격자 채움으로 전환된다 — 이 경로 게이트 하나로 지시가 전부 충족된다.
 *
 * 셸이 파생한 결과에만 적용한다: 파생 훅(집계 쿼리)은 손대지 않아 다른 섹션 영향이 0이다.
 */
export const gateRouteClusters = <T>(clusters: T[], pathname: string): T[] =>
  pathname === ROUTES.aiRoute ? [] : clusters;
