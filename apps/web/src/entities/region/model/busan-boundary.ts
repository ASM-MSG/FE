const toRing = (points: readonly LngLat[]): BoundaryRing =>
  points.map(([lng, lat]) => ({ lat, lng }));

/** 부산 행정경계 — 격자 클리핑(D7)·셀 포함 판정(AC 4)의 기준 */
export const BUSAN_BOUNDARY: BoundaryMultiPolygon = [
  [toRing(MAIN_RING), toRing(SUYEONG_BAY_HOLE)],
];

/** 부산 경계 bounding box — 격자 원점(GRID_ORIGIN = sw, D2)·뷰포트 컬링의 기준 */
export const BUSAN_BBOX: Bounds = BUSAN_BOUNDARY[0][0].reduce(
  (bbox, point) => ({
    sw: {
      lat: Math.min(bbox.sw.lat, point.lat),
      lng: Math.min(bbox.sw.lng, point.lng),
    },
    ne: {
      lat: Math.max(bbox.ne.lat, point.lat),
      lng: Math.max(bbox.ne.lng, point.lng),
    },
  }),
  {
    sw: { lat: Infinity, lng: Infinity },
    ne: { lat: -Infinity, lng: -Infinity },
  },
);
